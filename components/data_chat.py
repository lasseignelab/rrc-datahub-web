"""
Home-page chat box for asking questions about the DataHub's data.

Flow:
  type question (the field grows as it fills) -> Enter
    -> assets/data_chat_input.js sets the data-chat-send store
    -> submit_question() appends the question to the history store, clears
       the input, and records it as pending (so it shows up immediately)
    -> render_log() shows a "Searching the data…" message at the bottom of
       the log while answer_pending() sends the history to
       components.chat_assistant; the reply then takes its place (the log's
       aria-live region announces both)
    -> a question asked while an answer is on its way is queued (shown as
       "Up next") and ask_next_queued() sends it once that answer arrives,
       so Enter always leads to an answer and turns never interleave
    -> render_log() redraws the conversation from the history store
    -> [New chat] -> start_new_conversation() clears the history
       and queue (disabled while an answer is on its way)
    -> assets/data_chat_scroll.js scrolls the log to the newest exchange

The history store uses session storage, so the conversation survives page
changes and reloads in the same browser tab.
"""

import logging
from typing import Any

from dash import (
    Input,
    Output,
    State,
    callback,
    clientside_callback,
    dcc,
    html,
    no_update,
)

from components.chat_assistant import answer_question

logger = logging.getLogger(__name__)

EXAMPLE_QUESTION = "e.g. Which datasets include female mice?"
ERROR_REPLY = "Sorry, the data assistant hit an error. Please try again."
SEARCHING_MESSAGE = "Searching the data, this can take a few seconds…"

# Hyphenated ARIA props can't be Python keywords; typed as Any so the
# ** spread type-checks against html.Div's keyword arguments.
LOG_ARIA: dict[str, Any] = {
    "aria-live": "polite",
    "aria-label": "Conversation with data assistant",
}


layout = html.Div(
    [
        # Results first, question box under them, as in a typical chat. The
        # log is a fixed-height scroll box, so the box doesn't move down the
        # page as the conversation grows.
        html.Div(
            id="data-chat-log",
            className="data-chat-log",
            role="log",
            **LOG_ARIA,
        ),
        # Directly under the answers it applies to; hidden, like the log,
        # until the first question is asked.
        html.P(
            "Answers are generated by AI (OpenAI) from the DataHub's data and "
            "may contain mistakes. Check important results in the plots.",
            id="data-chat-disclaimer",
            className="data-chat-disclaimer",
            hidden=True,
        ),
        html.Div(
            [
                html.Label(
                    "Ask a question about the DataHub's data",
                    htmlFor="data-chat-input",
                    className="data-chat-label",
                ),
                html.Div(
                    [
                        # Grows with the question as it is typed; Enter asks
                        # and Shift+Enter adds a line (assets/
                        # data_chat_input.js, which also links the hint).
                        dcc.Textarea(
                            id="data-chat-input",
                            placeholder=EXAMPLE_QUESTION,
                            maxLength=1000,
                            rows=1,
                            className="data-chat-input",
                        ),
                        # Shown once there is a conversation to clear.
                        html.Button(
                            "New chat",
                            id="data-chat-new",
                            n_clicks=0,
                            className="btn btn-outline-primary data-chat-new",
                            hidden=True,
                        ),
                    ],
                    className="data-chat-input-row",
                ),
                # Visible, since there is no Ask button to show how to send.
                html.P(
                    "Press Enter to ask, or Shift+Enter for a new line.",
                    id="data-chat-input-hint",
                    className="data-chat-hint",
                ),
            ],
            className="data-chat-form",
        ),
        html.Div(id="data-chat-status", className="data-chat-status", role="status"),
        html.P(
            id="data-chat-queued",
            className="data-chat-queued",
            role="status",
            hidden=True,
        ),
        # Session storage keeps the conversation when the user follows a
        # link to the charts page and comes back, or reloads, within the same
        # tab; it is cleared when the tab closes and never shared across tabs.
        dcc.Store(id="data-chat-history", data=[], storage_type="session"),
        # Stays in memory: if it were restored after a reload mid-answer, the
        # chat would treat that question as still running and ignore new ones.
        dcc.Store(id="data-chat-pending", data=None),
        # Set by assets/data_chat_input.js (a fresh timestamp) when Enter is
        # pressed in the question field; it starts submit_question().
        dcc.Store(id="data-chat-send", data=None),
        # Questions asked while an answer is on its way, oldest first.
        dcc.Store(id="data-chat-queue", data=[]),
        # Runs only while questions are queued. Dash won't start a callback
        # again from changes its own run set off, so "answer arrived -> ask
        # the next question -> answer it" can't be a plain callback chain;
        # each tick is a fresh event that can start the next answer.
        dcc.Interval(id="data-chat-queue-timer", interval=500, disabled=True),
    ],
    className="data-chat",
)


@callback(
    Output("data-chat-history", "data"),
    Output("data-chat-pending", "data"),
    Output("data-chat-input", "value"),
    Output("data-chat-queue", "data"),
    Input("data-chat-send", "data"),
    State("data-chat-input", "value"),
    State("data-chat-history", "data"),
    State("data-chat-pending", "data"),
    State("data-chat-queue", "data"),
    prevent_initial_call=True,
)
def submit_question(_sent_at, question, history, pending, queue):
    """Send the typed question, or queue it if an answer is on its way."""
    question = (question or "").strip()
    if not question:
        return no_update, no_update, no_update, no_update
    if pending:
        # Asking now would interleave two answers; ask_next_queued() sends
        # it as soon as the current answer arrives.
        return no_update, no_update, "", (queue or []) + [question]
    history = (history or []) + [{"role": "user", "content": question}]
    return history, question, "", no_update


@callback(
    Output("data-chat-history", "data", allow_duplicate=True),
    Output("data-chat-pending", "data", allow_duplicate=True),
    Input("data-chat-pending", "data"),
    State("data-chat-history", "data"),
    prevent_initial_call=True,
    running=[
        # Clearing mid-answer would be undone when the answer arrives (it
        # is appended to the history read when the answer started).
        (Output("data-chat-new", "disabled"), True, False),
    ],
)
def answer_pending(pending, history):
    """Ask the assistant to answer the pending question."""
    if not pending:
        return no_update, no_update
    history = history or []
    # submit_question already appended the pending question as the last
    # entry; pass only the turns before it as context.
    try:
        reply = answer_question(history[:-1], pending)
    except Exception:  # pylint: disable=broad-exception-caught
        # answer_question already turns API errors into messages; this
        # catches anything else (e.g. a database failure in a tool) so the
        # question is always finished. Otherwise it would stay pending and
        # every later question would wait in the queue forever.
        logger.exception("Data chat failed to answer a question")
        reply = ERROR_REPLY
    return history + [{"role": "assistant", "content": reply}], None


@callback(
    Output("data-chat-history", "data", allow_duplicate=True),
    Output("data-chat-pending", "data", allow_duplicate=True),
    Output("data-chat-queue", "data", allow_duplicate=True),
    Input("data-chat-queue-timer", "n_intervals"),
    State("data-chat-history", "data"),
    State("data-chat-pending", "data"),
    State("data-chat-queue", "data"),
    prevent_initial_call=True,
)
def ask_next_queued(_n_intervals, history, pending, queue):
    """Once an answer has arrived, send the oldest queued question."""
    if pending or not queue:
        return no_update, no_update, no_update
    question, rest = queue[0], queue[1:]
    history = (history or []) + [{"role": "user", "content": question}]
    return history, question, rest


@callback(
    Output("data-chat-queued", "children"),
    Output("data-chat-queued", "hidden"),
    Output("data-chat-queue-timer", "disabled"),
    Input("data-chat-queue", "data"),
)
def render_queue(queue):
    """Show the questions waiting for the current answer, and run the queue
    timer only while there are any."""
    queue = queue or []
    if not queue:
        return "", True, True
    return "Up next: " + " · ".join(queue), False, False


def _message(speaker: str, body, class_name: str) -> html.Div:
    """One entry in the conversation log."""
    return html.Div(
        [html.Span(speaker, className="data-chat-speaker"), body],
        className="data-chat-message " + class_name,
    )


@callback(
    Output("data-chat-log", "children"),
    Output("data-chat-log", "className"),
    Output("data-chat-disclaimer", "hidden"),
    Output("data-chat-new", "hidden"),
    Input("data-chat-history", "data"),
    Input("data-chat-pending", "data"),
)
def render_log(history, pending=None):
    """Draw the conversation; the log and its disclaimer are hidden until
    the first question.

    While a question is pending, a "Searching the data…" message sits at
    the bottom of the log, where the user is looking for the answer.
    answer_pending() sets the reply and clears pending together, so the
    reply replaces it in one redraw.
    """
    history = history or []
    entries = []
    for turn in history:
        if turn["role"] == "user":
            entries.append(_message("You", html.P(turn["content"]), "data-chat-user"))
        else:
            entries.append(
                _message(
                    "Data assistant",
                    dcc.Markdown(turn["content"], link_target="_self"),
                    "data-chat-assistant",
                )
            )
    if pending and history and history[-1]["role"] == "user":
        entries.append(
            _message(
                "Data assistant",
                html.P(SEARCHING_MESSAGE),
                "data-chat-assistant data-chat-searching",
            )
        )
    class_name = "data-chat-log" + ("" if entries else " data-chat-log-empty")
    return entries, class_name, not entries, not entries


@callback(
    Output("data-chat-history", "data", allow_duplicate=True),
    Output("data-chat-queue", "data", allow_duplicate=True),
    Output("data-chat-pending", "data", allow_duplicate=True),
    Output("data-chat-status", "children", allow_duplicate=True),
    Input("data-chat-new", "n_clicks"),
    State("data-chat-pending", "data"),
    prevent_initial_call=True,
)
def start_new_conversation(_n_clicks, pending):
    """Clear the conversation, any queued questions and the pending one.

    The button is disabled while an answer runs (answer_pending's
    `running`), so this never discards an answer that is on its way.
    Clearing pending too means New chat always gets the chat going again,
    even if a question was left pending without an answer running.
    """
    # Only write pending when something is pending: any write starts
    # answer_pending, whose `running` would blank this status message.
    return [], [], None if pending else no_update, "Started a new chat."


# The button hides itself once the conversation is cleared, which would
# leave keyboard focus nowhere; put it back in the question field instead.
clientside_callback(
    """
    function(nClicks) {
        var field = document.getElementById("data-chat-input");
        if (nClicks && field) { field.focus(); }
        return window.dash_clientside.no_update;
    }
    """,
    Output("data-chat-input", "className"),
    Input("data-chat-new", "n_clicks"),
    prevent_initial_call=True,
)
