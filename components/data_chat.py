"""
Home-page chat box for asking questions about the DataHub's data.

Flow:
  type question -> [Ask] or Enter
    -> submit_question() appends the question to the history store, clears
       the input, and records it as pending (so it shows up immediately)
    -> answer_pending() sends the history to components.chat_assistant and
       appends the reply; while it runs, the button is disabled and a
       role="status" message tells screen readers the assistant is working
    -> render_log() redraws the conversation from the history store
"""

from typing import Any

from dash import Input, Output, State, callback, dcc, html, no_update

from components.chat_assistant import answer_question

EXAMPLE_QUESTION = "e.g. Which datasets include female mice?"

# Hyphenated ARIA props can't be Python keywords; typed as Any so the
# ** spread type-checks against html.Div's keyword arguments.
LOG_ARIA: dict[str, Any] = {
    "aria-live": "polite",
    "aria-label": "Conversation with data assistant",
}


layout = html.Div(
    [
        html.Div(
            [
                html.Label(
                    "Ask a question about the DataHub's data",
                    htmlFor="data-chat-input",
                    className="data-chat-label",
                ),
                html.Div(
                    [
                        dcc.Input(
                            id="data-chat-input",
                            type="text",
                            placeholder=EXAMPLE_QUESTION,
                            autoComplete="off",
                            maxLength=1000,
                            className="data-chat-input",
                        ),
                        html.Button(
                            "Ask",
                            id="data-chat-submit",
                            n_clicks=0,
                            className="btn btn-primary data-chat-submit",
                        ),
                    ],
                    className="data-chat-input-row",
                ),
            ],
            className="data-chat-form",
        ),
        html.Div(id="data-chat-status", className="data-chat-status", role="status"),
        html.P(
            "Answers are generated by AI (Google Gemini) from the DataHub's "
            "data and may contain mistakes. Check important results in the "
            "plots. Questions are sent to Google, which may use them to "
            "improve its products, so don't include private information.",
            className="data-chat-disclaimer",
        ),
        # The conversation sits below the box so the question field stays
        # in the same place on the page as the log grows.
        html.Div(
            id="data-chat-log",
            className="data-chat-log",
            role="log",
            **LOG_ARIA,
        ),
        dcc.Store(id="data-chat-history", data=[]),
        dcc.Store(id="data-chat-pending", data=None),
    ],
    className="data-chat",
)


@callback(
    Output("data-chat-history", "data"),
    Output("data-chat-pending", "data"),
    Output("data-chat-input", "value"),
    Input("data-chat-submit", "n_clicks"),
    Input("data-chat-input", "n_submit"),
    State("data-chat-input", "value"),
    State("data-chat-history", "data"),
    State("data-chat-pending", "data"),
    prevent_initial_call=True,
)
def submit_question(_n_clicks, _n_submit, question, history, pending):
    """Append the typed question to the history and mark it pending."""
    question = (question or "").strip()
    # Enter still fires while the button is disabled; ignore it until the
    # current answer arrives so turns cannot interleave.
    if not question or pending:
        return no_update, no_update, no_update
    history = (history or []) + [{"role": "user", "content": question}]
    return history, question, ""


@callback(
    Output("data-chat-history", "data", allow_duplicate=True),
    Output("data-chat-pending", "data", allow_duplicate=True),
    Input("data-chat-pending", "data"),
    State("data-chat-history", "data"),
    prevent_initial_call=True,
    running=[
        (Output("data-chat-submit", "disabled"), True, False),
        (
            Output("data-chat-status", "children"),
            "Searching the data, this can take a few seconds…",
            "",
        ),
    ],
)
def answer_pending(pending, history):
    """Ask the assistant to answer the pending question."""
    if not pending:
        return no_update, no_update
    history = history or []
    # submit_question already appended the pending question as the last
    # entry; pass only the turns before it as context.
    reply = answer_question(history[:-1], pending)
    return history + [{"role": "assistant", "content": reply}], None


@callback(
    Output("data-chat-log", "children"),
    Output("data-chat-log", "className"),
    Input("data-chat-history", "data"),
)
def render_log(history):
    """Draw the conversation; the log is hidden until the first question."""
    history = history or []
    entries = []
    for turn in history:
        is_user = turn["role"] == "user"
        entries.append(
            html.Div(
                [
                    html.Span(
                        "You" if is_user else "Data assistant",
                        className="data-chat-speaker",
                    ),
                    (
                        html.P(turn["content"])
                        if is_user
                        else dcc.Markdown(turn["content"], link_target="_self")
                    ),
                ],
                className=(
                    "data-chat-message "
                    + ("data-chat-user" if is_user else "data-chat-assistant")
                ),
            )
        )
    class_name = "data-chat-log" + ("" if entries else " data-chat-log-empty")
    return entries, class_name
